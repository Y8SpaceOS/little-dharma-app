import fs from 'fs';
const must = (p) => { if (!fs.existsSync(p)) throw new Error(`Missing required file: ${p}`); return fs.readFileSync(p,'utf8'); };
const onboarding = must('app/onboarding.tsx');
const index = must('app/index.tsx');
const gate = must('app/parent-gate.tsx');
const audit = must('docs/LITTLE_DHARMA_IMPLEMENTED_ROUTE_VISUAL_AUDIT.md');
const qa = must('docs/LITTLE_DHARMA_ONBOARDING_APP_SHELL_VISUAL_PARITY_V1_QA.md');
const queue = must('docs/MASTER_SPRINT_QUEUE.md');
const roadmap = must('docs/content/post-foundation-product-build-roadmap.csv');
const taskLog = must('docs/TASK_LOG.md');

const scoped = [onboarding,index,gate,audit,qa].join('\n');
if (/\bMoru\b/.test(scoped)) throw new Error('Moru found in Sprint 77 scope; use Luvlu only');
if (!/Luvlu/.test(scoped)) throw new Error('Luvlu must be present in Sprint 77 scope');
if (!/diya-lotus-sun/i.test(audit+qa)) throw new Error('Brand mark guidance (diya-lotus-sun led) missing in docs');
if (/\b(XP|coins|streaks?|leaderboard|ranking)\b/i.test(scoped)) throw new Error('Forbidden hard gamification language found');
if (/(microphone permission|audio recording permission)/i.test(scoped)) throw new Error('Permission wording must not be introduced');
if (/(backend|auth|cloud sync|CMS|analytics|telemetry)/i.test(scoped)) throw new Error('Forbidden platform scope found in Sprint 77 docs/source');
if (!/Sprint 77[\s\S]*Status:\*\* done/i.test(queue)) throw new Error('Sprint 77 must be done after implementation');
if (!/### Sprint 78[\s\S]*Status:\*\* not started/i.test(queue)) throw new Error('Sprint 78 must remain not started');
if (!/77,Onboarding \+ App Shell Prototype Reconstruction v1,[^\n]*,done,/.test(roadmap)) throw new Error('Roadmap CSV must mark Sprint 77 done');
if (!/78,Story Detail \+ Content Runtime Visual Integration v1,[^\n]*,not_started,/.test(roadmap)) throw new Error('Roadmap CSV must keep Sprint 78 not_started');
if (!/Sprint 60[\s\S]*conditional no-go/i.test(queue)) throw new Error('Sprint 60 conditional no-go must be preserved');
if (!/Sprint 14[\s\S]*not completed; deferred intentionally/i.test(queue) || !/Sprint 15[\s\S]*not completed; deferred intentionally/i.test(queue)) throw new Error('Sprint 14/15 deferred state must be preserved');
if (!/Sprint 77 completed: reconstructed onboarding \+ app shell runtime surfaces/.test(taskLog)) throw new Error('TASK_LOG append entry for Sprint 77 missing');
console.log('Sprint 77 onboarding + app shell visual parity validator passed.');
