import fs from 'fs';
const must = (p) => { if (!fs.existsSync(p)) throw new Error(`Missing required file: ${p}`); return fs.readFileSync(p,'utf8'); };
const onboarding = must('app/onboarding.tsx');
const index = must('app/index.tsx');
const gate = must('app/(parent)/profiles.tsx');
const audit = must('docs/LITTLE_DHARMA_IMPLEMENTED_ROUTE_VISUAL_AUDIT.md');
const qa = must('docs/LITTLE_DHARMA_ONBOARDING_APP_SHELL_VISUAL_PARITY_V1_QA.md');
const queue = must('docs/MASTER_SPRINT_QUEUE.md');
const registry = must('docs/LITTLE_DHARMA_PROTOTYPE_SCREEN_REGISTRY.md');
const roadmap = must('docs/content/post-foundation-product-build-roadmap.csv');
const taskLog = must('docs/TASK_LOG.md');

const scoped = [onboarding,index,gate,audit,qa].join('\n');
if (!/Exact onboarding access path/i.test(qa)) throw new Error('QA doc must document exact onboarding access path/steps');
if (!/Exact reset\/testing method/i.test(qa) || !/Reset Onboarding \(Local QA\)/.test(qa)) throw new Error('QA doc must document exact onboarding reset/testing method');
if (!/Luvlu Introduction/.test(onboarding)) throw new Error('Luvlu Introduction must be present in runtime onboarding');
if (!/Parent Promise/.test(onboarding)) throw new Error('Parent Promise must be present in runtime onboarding');
if (!/First World Preview/.test(onboarding)) throw new Error('First World Preview must be present in runtime onboarding');
const luvluCount = (onboarding.match(/Luvlu|luvlu/g) || []).length;
if (luvluCount < 3) throw new Error('Luvlu must appear visibly multiple times in onboarding runtime');
if (!/\/\(parent\)\/profiles/.test(onboarding + gate)) throw new Error('Accepted typed parent route /(parent)/profiles must be used');
if (/['"]\/?parent-gate['"]/.test(scoped) || /\/(parent)\/gate/.test(scoped)) throw new Error('Invalid parent hrefs found (/parent-gate or /(parent)/gate)');
if (!/### Sprint 78[\s\S]*Status:\*\* not started/i.test(queue)) throw new Error('Sprint 78 must remain not started in queue');
if (!/78,Story Detail \+ Content Runtime Visual Integration v1,[^\n]*,not_started,/.test(roadmap)) throw new Error('Sprint 78 must remain not_started in roadmap CSV');
if (!/Screens 01–08/.test(registry) && !/Screen 01/.test(registry)) throw new Error('Prototype screen registry appears unexpectedly changed/missing core references');
if (!/Sprint 77 completed: reconstructed onboarding \+ app shell runtime surfaces/.test(taskLog)) throw new Error('TASK_LOG Sprint 77 baseline entry missing');
console.log('Sprint 77 onboarding visual repair validator passed.');
